class Jacket {
    String brand;
    String size;
    String material;
    String color;
    boolean hasHood;

    Jacket() {}

    Jacket(String brand, String size, String material, String color, boolean hasHood) {
        this.brand = brand;
        this.size = size;
        this.material = material;
        this.color = color;
        this.hasHood = hasHood;
    }
}
